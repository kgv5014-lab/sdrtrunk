"""Remaking the summaries model without its image add-on (start-ollama.bat)."""

import subprocess

import pytest
import requests

from sdrtrunk_transcriber import ollama_text_only as tonly

MODEL_BLOB = r"C:\Users\Admin\.ollama\models\blobs\sha256-02d4"
PROJ_BLOB = r"C:\Users\Admin\.ollama\models\blobs\sha256-f836"
SIZES = {MODEL_BLOB: 5_700_000_000, PROJ_BLOB: 900_000_000}

MODELFILE = f"""# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM qwen-re:latest

FROM {MODEL_BLOB}
FROM {PROJ_BLOB}
TEMPLATE {{{{ .Prompt }}}}
PARAMETER num_ctx 8192
"""


def test_keeps_only_the_model_file():
    out = tonly.text_only_modelfile(MODELFILE, SIZES.__getitem__)
    assert f"FROM {MODEL_BLOB}" in out
    assert PROJ_BLOB not in out
    assert "PARAMETER num_ctx 8192" in out and "TEMPLATE" in out
    assert "# FROM qwen-re:latest" in out


def test_projector_listed_first_still_keeps_the_model():
    swapped = MODELFILE.replace(f"FROM {MODEL_BLOB}\nFROM {PROJ_BLOB}", f"FROM {PROJ_BLOB}\nFROM {MODEL_BLOB}")
    out = tonly.text_only_modelfile(swapped, SIZES.__getitem__)
    assert MODEL_BLOB in out and PROJ_BLOB not in out


def test_no_from_line_is_an_error():
    with pytest.raises(ValueError):
        tonly.text_only_modelfile("PARAMETER num_ctx 8192\n", SIZES.__getitem__)


def test_addon_only_counts_a_separate_projector():
    assert tonly.has_image_addon({"projector_info": {"clip.has_vision_encoder": True}})
    assert not tonly.has_image_addon({"capabilities": ["completion", "vision"]})
    assert not tonly.has_image_addon({})


class Fake:
    def __init__(self, models, create_ok=True):
        self.models = models  # name -> show dict
        self.create_ok = create_ok
        self.commands = []

    def show(self, url, model):
        if model not in self.models:
            raise requests.HTTPError("404")
        return self.models[model]

    def run(self, *args):
        self.commands.append(args)
        if args[0] == "cp":
            self.models[args[2]] = dict(self.models[args[1]])
        elif args[0] == "create":
            if not self.create_ok:
                return subprocess.CompletedProcess(args, 1, "", "boom")
            self.models[args[1]] = {"modelfile": "FROM x\n"}
        return subprocess.CompletedProcess(args, 0, "", "")


@pytest.fixture
def fake(monkeypatch):
    f = Fake({"qwen-re": {"modelfile": MODELFILE, "projector_info": {"a": 1}}})
    monkeypatch.setattr(tonly, "show", f.show)
    monkeypatch.setattr(tonly, "run", f.run)
    monkeypatch.setattr(tonly.os.path, "getsize", SIZES.__getitem__)
    return f


def test_backs_up_then_remakes(fake):
    msg = tonly.drop_image_addon("http://x", "qwen-re")
    assert [c[0] for c in fake.commands] == ["cp", "create"]
    assert fake.commands[0] == ("cp", "qwen-re", "qwen-re-with-images")
    assert "projector_info" in fake.models["qwen-re-with-images"]
    assert "projector_info" not in fake.models["qwen-re"]
    assert "qwen-re-with-images" in msg
    # second start: nothing to do
    fake.commands.clear()
    assert "nothing to do" in tonly.drop_image_addon("http://x", "qwen-re")
    assert fake.commands == []


def test_existing_backup_is_not_overwritten(fake):
    fake.models["qwen-re-with-images"] = {"old": True}
    tonly.drop_image_addon("http://x", "qwen-re")
    assert [c[0] for c in fake.commands] == ["create"]
    assert fake.models["qwen-re-with-images"] == {"old": True}


def test_failed_create_leaves_model_alone(fake):
    fake.create_ok = False
    with pytest.raises(RuntimeError):
        tonly.drop_image_addon("http://x", "qwen-re")
    assert "projector_info" in fake.models["qwen-re"]


def test_main_never_fails(tmp_path, monkeypatch, capsys):
    cfg = tmp_path / "config.toml"
    cfg.write_text('[summaries]\nenabled = true\nmodel = "qwen-re"\n')
    monkeypatch.setattr(tonly, "drop_image_addon", lambda url, model: (_ for _ in ()).throw(OSError("no ollama")))
    assert tonly.main(["x", str(cfg)]) == 0
    assert "keeps working as before" in capsys.readouterr().out


def test_main_skips_when_turned_off(tmp_path, monkeypatch):
    cfg = tmp_path / "config.toml"
    cfg.write_text('[summaries]\nenabled = true\ndrop_image_addon = false\n')
    monkeypatch.setattr(tonly, "drop_image_addon", lambda *a: pytest.fail("should not run"))
    assert tonly.main(["x", str(cfg)]) == 0
